"""Milestone 7: automatic taxonomy of the spans the best configuration leaks.

Usage:  python scripts/error_taxonomy.py

Best configuration: crf+regex+presidio (M4 ensemble), typed masking. Under typed masking a gold
span leaks exactly when no detected span covers it (its characters are copied unchanged), so
the leaked spans are the type-agnostic false negatives of the stored run. They are categorised
by privgate.bench.taxonomy (mapped label, raw label, untargeted raw label, format, length,
position). Outputs: results/m7/error_taxonomy.json (counts and shares), docs/error-analysis.md
(tables) and docs/error-examples.md (10 seeded +-30 character examples per top category).
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

from privgate.bench.cli import _load
from privgate.bench.errors import collect_errors, excerpt
from privgate.bench.registry import M3_DETECTORS, members
from privgate.bench.runner import PREDICTIONS, read_predictions, write_json
from privgate.bench.sets import DEV_SET, SET_NAMES
from privgate.bench.support import untargeted_by_all
from privgate.bench.taxonomy import (
    DIMENSIONS,
    UNTARGETED,
    categorize_all,
    count_categories,
    ranked,
    seeded_examples,
)
from privgate.data import gretel, nemotron
from privgate.spans import EntityType

DATA = Path("data")
DETECTOR = "crf+regex+presidio"
RUN_ROOT = Path("results/m4")
M3_ROOT = Path("results/m3")
OUT_JSON = Path("results/m7/error_taxonomy.json")
OUT_DOC = Path("docs/error-analysis.md")
OUT_EXAMPLES = Path("docs/error-examples.md")
DATASET_OF = {"nemotron_dev_2k": nemotron.DATASET, "nemotron_test_5k": nemotron.DATASET,
              "gretel_en_test": gretel.DATASET}
TOP_RAW = 15
TOP_FOR_EXAMPLES = 3          # largest categories of mapped label / raw label / shape / position
EXAMPLE_DIMENSIONS = ("mapped_label", "raw_label", "shape", "position")
EXAMPLES_PER_CATEGORY = 10
CONTEXT = 30
TITLES = {"mapped_label": "Mapped label", "raw_label": f"Raw label (top {TOP_RAW})",
          "untargeted": "Raw label targeted by an M3 detector?", "shape": "Format of the value",
          "length": "Length (characters)", "position": "Position"}
ATTRIBUTION = (
    "The excerpts are SYNTHETIC text from Nemotron-PII by NVIDIA Corporation "
    "(CC BY 4.0, https://huggingface.co/datasets/nvidia/Nemotron-PII) and from "
    "gretelai/synthetic_pii_finance_multilingual (Apache-2.0). Changes: cut to +-"
    f"{CONTEXT} characters around the span, the span marked with ⟦ ⟧, line breaks shown as ⏎. "
    "No real person is described.")


def untargeted_labels(dataset: str) -> frozenset[str]:
    dets = {}
    for d in M3_DETECTORS:
        meta = json.loads((M3_ROOT / DEV_SET / d / "metrics.json").read_text(encoding="utf-8"))
        dets[d] = (members(d), [EntityType(x) for x in meta["supported_labels"]])
    return untargeted_by_all(dets, dataset)


def analyse(set_name: str) -> tuple[dict, list, dict]:
    docs, sha, raw = _load(DATA, set_name)
    run = RUN_ROOT / set_name / DETECTOR
    meta = json.loads((run / "metrics.json").read_text(encoding="utf-8"))
    if meta["set_sha256"] != sha:
        raise SystemExit(f"{run} was scored on another version of {set_name}")
    preds, _ = read_predictions(run / PREDICTIONS, docs)
    fns, _ = collect_errors(docs, preds, raw)
    texts = {d.doc_id: d.text for d in docs}
    items = categorize_all(fns, texts, untargeted_labels(DATASET_OF[set_name]))
    counts = count_categories(items)
    gold = sum(len(d.spans) for d in docs)
    total = len(items)
    dims = {dim: ranked(counts[dim], total, TOP_RAW if dim == "raw_label" else None)
            for dim in DIMENSIONS}
    tops = []
    for dim in EXAMPLE_DIMENSIONS:
        tops += [(dim, r["category"]) for r in dims[dim][:TOP_FOR_EXAMPLES]]
    tops.append(("untargeted", UNTARGETED))
    summary = {"set_sha256": sha, "documents": len(docs), "gold_spans": gold,
               "leaked_spans": total, "leaked_share_of_gold_spans": total / gold if gold else 0,
               "dimensions": dims,
               "top_categories": [{"dimension": d, "category": c} for d, c in tops]}
    return summary, items, texts


def md_table(rows: list[dict]) -> list[str]:
    lines = ["| category | spans | share of leaked spans |", "|---|---|---|"]
    lines += [f"| {r['category']} | {r['count']} | {r['share']:.3f} |" for r in rows]
    return lines


def render_doc(result: dict) -> str:
    lines = [
        "# Error analysis: what the best configuration leaks",
        "",
        ("Generated by `scripts/error_taxonomy.py` from `results/m7/error_taxonomy.json`. "
        f"Configuration `{DETECTOR}` with typed masking: a gold span leaks when no detected span "
        "covers it (a type-agnostic false negative of the stored run). Categories are assigned "
        "automatically by `privgate.bench.taxonomy`; each dimension partitions the leaked spans "
        "(counts sum to the total). Examples: [error-examples.md](error-examples.md)."),
        "",
        ("Definitions. **Format**: first matching rule of *all digits* (every non-space "
        "character is a digit), *contains punctuation* (any non-alphanumeric, non-space "
        "character), *mixed alphanumeric*, *title-case word(s)*, *lowercase word(s)*, *other "
        "letters*. **Position**: *table / delimited line* (the line has two or more `|` or a "
        "tab), *key: value line* (the line starts with a short label followed by `:` or `=` and "
        "the span lies after it), otherwise *prose*. **Untargeted**: the raw label is targeted "
        "by none of the five M3 detectors (privgate.bench.support)."),
        "",
    ]
    for set_name in SET_NAMES:
        r = result["sets"][set_name]
        lines += [f"## `{set_name}`", "",
                  (f"{r['leaked_spans']} of {r['gold_spans']} gold spans leak "
                  f"({r['leaked_share_of_gold_spans']:.3f}) in {r['documents']} documents."), ""]
        for dim in DIMENSIONS:
            lines += [f"**{TITLES[dim]}**", "", *md_table(r["dimensions"][dim]), ""]
    return "\n".join(lines).rstrip() + "\n"


def render_examples(result: dict, analysed: dict) -> str:
    lines = ["# Examples of leaked spans", "", ATTRIBUTION, "",
             (f"Generated by `scripts/error_taxonomy.py`: {EXAMPLES_PER_CATEGORY} examples per top "
             "category and set, drawn with a seed derived from (0, set, dimension, category). "
             "The top categories are the "
             f"{TOP_FOR_EXAMPLES} largest of mapped label, raw label, format and position, plus "
             "the untargeted raw labels."), ""]
    for set_name in SET_NAMES:
        items, texts = analysed[set_name]
        lines += [f"## `{set_name}`", ""]
        for top in result["sets"][set_name]["top_categories"]:
            dim, cat = top["dimension"], top["category"]
            n = sum(1 for i in items if i.categories[dim] == cat)
            lines += [f"### {TITLES[dim]}: {cat} ({n} spans)", ""]
            for k, case in enumerate(seeded_examples(items, dim, cat, set_name,
                                                     EXAMPLES_PER_CATEGORY), 1):
                s = case.span
                shown = excerpt(texts[case.doc_id], s, CONTEXT)
                lines += [(f"{k}. `{case.doc_id}` gold {s.label.value}, raw "
                          f"`{case.raw_label}`: {shown!r}")]
            lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def main() -> int:
    result = {"detector": DETECTOR, "masking": "typed", "sets": {}}
    analysed = {}
    for set_name in SET_NAMES:
        summary, items, texts = analyse(set_name)
        result["sets"][set_name] = summary
        analysed[set_name] = (items, texts)
        print(f"{set_name}: {summary['leaked_spans']} leaked of {summary['gold_spans']}")
    write_json(OUT_JSON, result)
    for path, text in ((OUT_DOC, render_doc(result)),
                       (OUT_EXAMPLES, render_examples(result, analysed))):
        path.write_text(text, encoding="utf-8", newline="\n")
        print(f"wrote {path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
