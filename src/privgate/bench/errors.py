"""Error analysis: sampled type-agnostic false negatives and false positives with context.

Errors are exactly the ones the metrics count (privgate.evaluation.match_spans,
type-agnostic mode). All errors of a run are sorted (doc_id, start, end, label) and
``random.Random(seed).sample`` draws the examples, so the sample is reproducible and does
not depend on file order.
"""

from __future__ import annotations

import random
from collections.abc import Mapping, Sequence
from dataclasses import dataclass

from privgate.data.documents import Document
from privgate.evaluation import match_spans
from privgate.spans import Span

N_EXAMPLES = 15
CONTEXT_CHARS = 40
SEED = 0

ATTRIBUTION = (
    "The texts below are SYNTHETIC excerpts of Nemotron-PII by NVIDIA Corporation "
    "(https://huggingface.co/datasets/nvidia/Nemotron-PII), licensed under CC BY 4.0 "
    "(https://creativecommons.org/licenses/by/4.0/). Changes: excerpts cut to +-"
    f"{CONTEXT_CHARS} characters around the span, the span marked with ⟦ ⟧, line breaks "
    "shown as ⏎. No real person is described."
)


@dataclass(frozen=True)
class ErrorCase:
    doc_id: str
    span: Span
    raw_label: str | None = None


def collect_errors(docs: Sequence[Document], preds: Sequence[Sequence[Span]],
                   raw_labels: Mapping[str, list[str]] | None = None
                   ) -> tuple[list[ErrorCase], list[ErrorCase]]:
    """All type-agnostic false negatives and false positives of a run."""
    fns, fps = [], []
    for doc, pred in zip(docs, preds):
        _, missed, spurious = match_spans(list(doc.spans), list(pred), "type_agnostic")
        raws = dict(zip(doc.spans, raw_labels[doc.doc_id])) if raw_labels else {}
        fns += [ErrorCase(doc.doc_id, g, raws.get(g)) for g in missed]
        fps += [ErrorCase(doc.doc_id, p) for p in spurious]
    return fns, fps


def sample_errors(cases: Sequence[ErrorCase], n: int = N_EXAMPLES,
                  seed: int = SEED) -> list[ErrorCase]:
    ordered = sorted(cases, key=lambda c: (c.doc_id, c.span.start, c.span.end,
                                           c.span.label.value))
    return random.Random(seed).sample(ordered, min(n, len(ordered)))


def excerpt(text: str, span: Span, width: int = CONTEXT_CHARS) -> str:
    before = text[max(0, span.start - width):span.start]
    after = text[span.end:span.end + width]
    shown = f"{before}⟦{text[span.start:span.end]}⟧{after}"
    return shown.replace("\r\n", "⏎").replace("\n", "⏎").replace("\r", "⏎").replace("~~~", "~ ~ ~")


def render_errors(detector: str, set_name: str, docs: Sequence[Document],
                  fns: Sequence[ErrorCase], fps: Sequence[ErrorCase],
                  totals: tuple[int, int]) -> str:
    texts = {d.doc_id: d.text for d in docs}
    lines = [
        f"# Error analysis: `{detector}` on `{set_name}`",
        "",
        ("Generated by `python -m privgate.bench errors`. Type-agnostic matching; examples "
         f"drawn with seed {SEED} from {totals[0]} false negatives and {totals[1]} false "
         "positives."),
        "",
        ATTRIBUTION,
        "",
    ]
    for title, cases, kind in (("False negatives (gold span not detected)", fns, "FN"),
                               ("False positives (detection without gold span)", fps, "FP")):
        lines += [f"## {title}", ""]
        for i, case in enumerate(cases, 1):
            s = case.span
            who = f"gold {s.label.value}" if kind == "FN" else f"predicted {s.label.value}"
            raw = f", raw label `{case.raw_label}`" if case.raw_label else ""
            lines += [f"{i}. `{case.doc_id}` [{s.start}, {s.end}) {who}{raw}", "",
                      "   ~~~text", f"   {excerpt(texts[case.doc_id], s)}", "   ~~~", ""]
    return "\n".join(lines).rstrip() + "\n"
